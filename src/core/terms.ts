export function isFiller(word: string): boolean {
  return FILLERS.has(word);
}

const KEYS_LONGEST_FIRST = Object.keys(KO_EN).sort((a, b) => b.length - a.length);

/**
 * 질의 낱말 하나 → 영어 확장 낱말들 (없으면 빈 배열).
 * 활용형("제한하는", "충돌할", "인증을")도 잡도록 사전 낱말로 **시작하는** 가장 긴 항목을 쓴다.
 */
export function expandKorean(word: string): string[] {
  if (!/^[가-힣]/.test(word)) return [];
  const key = KEYS_LONGEST_FIRST.find((candidate) => word.startsWith(candidate));
  return key ? KO_EN[key].split(" ") : [];
}
